export const TICKETS: { number: string; color: TicketColor }[] = (Object.keys(SHEET) as TicketColor[]).flatMap((color) =>
  SHEET[color].map((number) => ({ number, color })),
);

const BY_NUMBER = new Map(TICKETS.map((t) => [t.number, t]));

export function ticketColor(number: string): TicketColor {
  return BY_NUMBER.get(number)?.color ?? "blue";
}

export function isValidTicket(number: string) {
  return BY_NUMBER.has(number);
}
